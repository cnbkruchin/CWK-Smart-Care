#!/usr/bin/env node
// Build gas-dist/ from src/ and frontend/ (DECISIONS D-002):
//   gas-dist/Code.js          esbuild IIFE bundle → single global `CWK` (ES2019, no import/export)
//   gas-dist/Entrypoints.js   public functions allowlist (copied from src/entry/gas-entrypoints.js)
//   gas-dist/App.html         frontend bundle + CSS inlined (served by doGet)
//   gas-dist/appsscript.json  manifest (scopes, advanced services, web app settings)
// Usage: node tools/build-gas.mjs [--check]   (--check fails when committed gas-dist is stale)

import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';
import * as esbuild from 'esbuild';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT = path.join(ROOT, 'gas-dist');
const CHECK = process.argv.includes('--check');
const pkg = JSON.parse(fs.readFileSync(path.join(ROOT, 'package.json'), 'utf8'));

async function bundle(entry, platform, globalName) {
  const r = await esbuild.build({
    entryPoints: [path.join(ROOT, entry)], bundle: true, write: false, format: 'iife', globalName, target: 'es2019', platform,
    charset: 'utf8', legalComments: 'none', minify: false, treeShaking: true, logLevel: 'silent',
  });
  return r.outputFiles[0].text;
}

const files = new Map();
const code = await bundle('src/entry/gas-main.js', 'neutral', 'CWK');
if (/^\s*(import|export)\s/m.test(code)) throw new Error('Code.js contains ES module syntax');
files.set('Code.js', `/* CWK Smart Care ${pkg.version} — generated by tools/build-gas.mjs from src/. DO NOT EDIT; edit src/ and rebuild. */\n${code}`);
files.set('Entrypoints.js', fs.readFileSync(path.join(ROOT, 'src/entry/gas-entrypoints.js'), 'utf8'));
files.set('appsscript.json', fs.readFileSync(path.join(ROOT, 'src/entry/appsscript.json'), 'utf8'));

const feJs = (await bundle('frontend/src/main.js', 'browser', 'CWKApp')).replace(/<\/script/gi, '<\\/script');
const feCss = fs.readFileSync(path.join(ROOT, 'frontend/src/styles.css'), 'utf8');
const template = fs.readFileSync(path.join(ROOT, 'frontend/src/index.html'), 'utf8');
const html = template.replace('/*__STYLE__*/', () => feCss).replace('/*__SCRIPT__*/', () => feJs);
if (!html.includes('/*__CWK_BOOT__*/null')) throw new Error('App.html must contain the boot placeholder');
files.set('App.html', html);

const sourceHash = crypto.createHash('sha256');
for (const [name, content] of [...files].sort()) sourceHash.update(name).update(content);
files.set('BUILD_INFO.json', JSON.stringify({ app_version: pkg.version, build_hash: sourceHash.digest('hex').slice(0, 16), files: [...files.keys()].sort(), note: 'Copy every .js/.html file and appsscript.json into the Apps Script project (clasp: rootDir=gas-dist).' }, null, 2) + '\n');

let stale = 0;
for (const [name, content] of files) {
  const p = path.join(OUT, name);
  const cur = fs.existsSync(p) ? fs.readFileSync(p, 'utf8') : null;
  if (CHECK) { if (cur !== content) { console.error(`STALE: gas-dist/${name}`); stale++; } }
  else if (cur !== content) { fs.mkdirSync(OUT, { recursive: true }); fs.writeFileSync(p, content); console.log(`wrote gas-dist/${name} (${(content.length / 1024).toFixed(0)} KB)`); }
}
if (CHECK && stale) { console.error('gas-dist is stale — run npm run build'); process.exit(1); }
if (CHECK) console.log('gas-dist up to date');
