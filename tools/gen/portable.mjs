// Portable format artifacts: JSON Schemas of the manifest and the attachment index, and the docs bundle
// (app version + docs/PORTABLE_FORMAT.md + docs/MIGRATION_RUNBOOK_TH.md) embedded in every package so a
// package always carries the documentation of the version that produced it.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { MANIFEST_SCHEMA, ATTACHMENT_INDEX_SCHEMA } from '../../src/application/migration/format.js';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');

export function generate() {
  const pkg = JSON.parse(fs.readFileSync(path.join(ROOT, 'package.json'), 'utf8'));
  const docs = {};
  for (const name of ['PORTABLE_FORMAT.md', 'MIGRATION_RUNBOOK_TH.md']) docs[name] = fs.readFileSync(path.join(ROOT, 'docs', name), 'utf8');
  const bundle = [
    '// GENERATED by tools/gen-docs.mjs (tools/gen/portable.mjs) — DO NOT EDIT. Docs and version shipped inside every portable package.',
    `export const APP_VERSION = ${JSON.stringify(pkg.version)};`,
    `export const PACKAGE_DOCS = ${JSON.stringify(docs, null, 2)};`,
    '',
  ].join('\n');
  return {
    'schema/portable/manifest.schema.json': JSON.stringify(MANIFEST_SCHEMA, null, 2),
    'schema/portable/attachment-index.schema.json': JSON.stringify(ATTACHMENT_INDEX_SCHEMA, null, 2),
    'src/application/migration/docs-bundle.js': bundle,
  };
}
