export function enumValues(name) {
  const en = ENUMS[name];
  if (!en) throw new Error(`unknown enum ${name}`);
  return en.values;
}

export function enumLabel(name, value) {
  return (ENUMS[name] && ENUMS[name].th[value]) || value;
}
